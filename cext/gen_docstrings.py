"""Generates C++ docstring constants for the public APIs defined in the C++ extension
from the docstrings in _cext.pyi, so that the stubs are the single source of the documentation.

Usage: gen_docstrings.py <path to _cext.pyi> <output header>
"""

import ast
import inspect
import sys

CLASSES = ("Tile", "Scalar", "Vector", "Pointer", "OpaqueValue")


def is_property(func: ast.FunctionDef) -> bool:
    return any(isinstance(d, ast.Name) and d.id == "property" for d in func.decorator_list)


def format_params(args: ast.arguments, is_method: bool,
                  literal_defaults_only: bool) -> list[str] | None:
    """Formats the parameters, except `self`. Returns None if `literal_defaults_only` is set and
    a default isn't a literal."""
    def format_default(node: ast.expr) -> str | None:
        if isinstance(node, ast.Constant):
            return repr(node.value)
        return None if literal_defaults_only else ast.unparse(node)

    posonly = list(args.posonlyargs)
    regular = list(args.args)
    # Defaults apply to the last positional parameters
    defaults = [None] * (len(posonly) + len(regular) - len(args.defaults)) + list(args.defaults)
    if is_method:
        first = posonly.pop(0) if posonly else regular.pop(0)
        assert first.arg == "self", "The first parameter of a method must be `self`"
        defaults.pop(0)

    params = []
    positional = posonly + regular
    for i, arg in enumerate(positional):
        text = arg.arg
        if defaults[i] is not None:
            value = format_default(defaults[i])
            if value is None:
                return None
            text += "=" + value
        params.append(text)
        if i == len(posonly) - 1:
            params.append("/")

    if args.vararg is not None:
        params.append("*" + args.vararg.arg)
    elif args.kwonlyargs:
        params.append("*")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults, strict=True):
        text = arg.arg
        if default is not None:
            value = format_default(default)
            if value is None:
                return None
            text += "=" + value
        params.append(text)
    if args.kwarg is not None:
        params.append("**" + args.kwarg.arg)
    return params


def signature(name: str, args: ast.arguments, is_method: bool, bind_self: bool) -> str:
    """Returns a text signature (e.g. "reshape($self, /, shape)\\n--\\n\\n"), which is what
    inspect.signature() reads. It can't express non-literal defaults (e.g. enum members), so
    in that case, returns the signature as the first line of the docstring instead, where Sphinx
    and help() still show it."""
    params = format_params(args, is_method, literal_defaults_only=True)
    if params is not None:
        if bind_self:
            params = ["$self"] + (params if "/" in params else ["/"] + params)
        return f"{name}({', '.join(params)})\n--\n\n"
    params = format_params(args, is_method, literal_defaults_only=False)
    return f"{name}({', '.join(params)})\n\n"


def c_string_literal(text: str) -> str:
    lines = text.split("\n")
    parts = []
    for i, line in enumerate(lines):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        if i < len(lines) - 1:
            escaped += "\\n"
        if escaped:
            parts.append(f'"{escaped}"')
    if not parts:
        return '""'
    return "\n        ".join(parts)


def make_doc(signature: str | None, docstring: str | None) -> str | None:
    doc = inspect.cleandoc(docstring) if docstring is not None else None
    if signature is None:
        return doc
    return signature + (doc or "")


def generate(pyi_source: str) -> str:
    tree = ast.parse(pyi_source)
    classes = {node.name: node for node in tree.body if isinstance(node, ast.ClassDef)}

    out = [
        "// Generated by cext/gen_docstrings.py from src/cuda/tile/_cext.pyi. Do not edit.",
        "",
        "#pragma once",
        "",
    ]

    def emit(name: str, doc: str | None):
        value = "nullptr" if doc is None else c_string_literal(doc)
        out.append(f"inline constexpr const char* {name} =\n        {value};")
        out.append("")

    for class_name in CLASSES:
        cls = classes[class_name]
        methods = [m for m in cls.body if isinstance(m, ast.FunctionDef)]

        init = next((m for m in methods if m.name == "__init__"), None)
        class_signature = None
        if init is not None:
            class_signature = signature(class_name, init.args, is_method=True, bind_self=False)
        emit(f"kDoc_{class_name}", make_doc(class_signature, ast.get_docstring(cls, clean=False)))

        for method in methods:
            if method.name.startswith("__"):
                continue
            docstring = ast.get_docstring(method, clean=False)
            if is_property(method):
                emit(f"kDoc_{class_name}_{method.name}", make_doc(None, docstring))
            else:
                method_signature = signature(method.name, method.args, is_method=True,
                                             bind_self=True)
                emit(f"kDoc_{class_name}_{method.name}", make_doc(method_signature, docstring))

    return "\n".join(out)


def main():
    pyi_path, out_path = sys.argv[1:]
    with open(pyi_path) as f:
        header = generate(f.read())
    with open(out_path, "w") as f:
        f.write(header)


if __name__ == "__main__":
    main()
